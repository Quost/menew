import AppKit
import CryptoKit
import ApplicationServices

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, file }

    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var date = Date()
    var sourceApp: String?
    var sourceBundle: String?
    var pinned = false
    /// Preenchido só para snippets (não vão para o histórico)
    var snippetTitle: String?
    /// Nota de senhas mostrada no ⌘⇧V: o segredo só sai das Chaves depois do Touch ID, na hora de colar
    var secretNoteID: UUID?
    /// Texto lido da imagem (no Mac, em segundo plano), para achar prints pela busca. "" = já lida, sem texto.
    var ocrText: String?

    var preview: String {
        guard let t = text else { return "" }
        let collapsed = t.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return String(collapsed.prefix(300))
    }

    /// Primeira linha com conteúdo, para a lista
    var title: String {
        guard let t = text else { return "" }
        let line = t.split(whereSeparator: \.isNewline).first { !$0.trimmingCharacters(in: .whitespaces).isEmpty } ?? ""
        return String(line.trimmingCharacters(in: .whitespaces).prefix(200))
    }

    var isCode: Bool {
        guard kind == .text, let t = text, t.contains("\n") else { return false }
        return ["{", "=>", "func ", "def ", "</", "import ", "const ", "SELECT "].contains { t.contains($0) }
    }

    var url: URL? {
        guard kind == .text, let t = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              !t.contains(" "), let u = URL(string: t), let s = u.scheme, ["http", "https"].contains(s) else { return nil }
        return u
    }

    /// "#1e90ff" ou "1e90ff" → cor, para mostrar uma amostra na lista
    var hexColor: NSColor? {
        guard kind == .text, var t = text?.trimmingCharacters(in: .whitespacesAndNewlines) else { return nil }
        if t.hasPrefix("#") { t.removeFirst() }
        guard t.count == 6, let v = UInt32(t, radix: 16) else { return nil }
        return NSColor(srgbRed: CGFloat((v >> 16) & 0xff) / 255, green: CGFloat((v >> 8) & 0xff) / 255,
                       blue: CGFloat(v & 0xff) / 255, alpha: 1)
    }

    func sameContent(as o: ClipItem) -> Bool {
        kind == o.kind && (kind == .image ? imageFile == o.imageFile : text == o.text)
    }
}

enum ClipFilter: String, CaseIterable {
    case all, text, link, image, file, pinned, snippets, passwords
    var label: String {
        switch self {
        case .all: L("Tudo")
        case .text: L("Texto")
        case .link: L("Links")
        case .image: L("Imagens")
        case .file: L("Arquivos")
        case .pinned: L("Fixados")
        case .snippets: L("Snippets")
        case .passwords: L("Senhas")
        }
    }
    var icon: String {
        switch self {
        case .all: "square.stack"
        case .text: "text.alignleft"
        case .link: "link"
        case .image: "photo"
        case .file: "doc"
        case .pinned: "pin"
        case .snippets: "text.badge.star"
        case .passwords: "key.fill"
        }
    }
    func matches(_ i: ClipItem) -> Bool {
        switch self {
        case .all: true
        case .text: i.kind == .text && i.url == nil
        case .link: i.url != nil
        case .image: i.kind == .image
        case .file: i.kind == .file
        case .pinned: i.pinned
        case .snippets, .passwords: false
        }
    }
}

@MainActor
final class ClipboardManager: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    /// Tipos que gerenciadores de senha e afins marcam como "não guarde isso"
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    let dir: URL
    let imagesDir: URL
    private var historyURL: URL { dir.appendingPathComponent("history.json") }
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var cleanupTimer: Timer?
    private let thumbCache = NSCache<NSString, NSImage>()

    var defaults: UserDefaults { .standard }
    private var isDemo = false
    lazy var snippets = SnippetStore(dir: isDemo ? nil : dir)

    /// Histórico fictício, usado só para gerar capturas de tela da interface
    static func demo() -> ClipboardManager {
