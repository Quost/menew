            ClipItem(kind: .text, text: "https://github.com/Quost/menew", date: now.addingTimeInterval(-300), sourceApp: "Safari", sourceBundle: "com.apple.Safari"),
            ClipItem(kind: .text, text: "#6C5CE7", date: now.addingTimeInterval(-900), sourceApp: "Figma", sourceBundle: "com.figma.Desktop"),
            ClipItem(kind: .text, text: "func greet(_ name: String) -> String {\n    return \"\(pt ? "Olá" : "Hello"), \\(name)!\"\n}", date: now.addingTimeInterval(-1800), sourceApp: "Xcode", sourceBundle: "com.apple.dt.Xcode", pinned: true),
            ClipItem(kind: .file, text: "/System/Applications/Calculator.app", date: now.addingTimeInterval(-3600), sourceApp: "Finder", sourceBundle: "com.apple.finder"),
            ClipItem(kind: .text, text: pt ? "matheus@exemplo.com" : "hello@example.com", date: now.addingTimeInterval(-7200), sourceApp: "Mail", sourceBundle: "com.apple.mail"),
            ClipItem(kind: .text, text: pt ? "Lista de compras: café, pão, queijo, frutas" : "Groceries: coffee, bread, cheese, fruit", date: now.addingTimeInterval(-86400), sourceApp: pt ? "Notas" : "Notes", sourceBundle: "com.apple.Notes"),
        ]
        return m
    }

    init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        dir = base.appendingPathComponent("Menew", isDirectory: true)
        imagesDir = dir.appendingPathComponent("images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
    }

    func start() {
        load()
        pruneAndSaveIfNeeded()
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.15
        // Itens vencidos saem mesmo sem nada novo ser copiado
        cleanupTimer = Timer.scheduledTimer(withTimeInterval: 3600, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.pruneAndSaveIfNeeded() }
        }
    }

    /// Chamado também quando o ajuste de dias muda
    func pruneAndSaveIfNeeded() {
        let before = items.count
        prune()
        if items.count != before { save() }
    }

    // MARK: Captura

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        // Módulo desligado: nem o conteúdo é lido
        if !Module.clipboard.isOn || Self.isPaused { return }

        let types = (pb.types ?? []).map(\.rawValue)
        if defaults.bool(forKey: "ignoreConcealed"), types.contains(where: ignoredTypes.contains) { return }

        let front = NSWorkspace.shared.frontmostApplication
        if let bundle = front?.bundleIdentifier, ignoredApps.contains(bundle) { return }
        var item: ClipItem?

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = ClipItem(kind: .file, text: urls.map(\.path).joined(separator: "\n"))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item = ClipItem(kind: .text, text: s)
        } else if let img = NSImage(pasteboard: pb), let tiff = img.tiffRepresentation,
                  let rep = NSBitmapImageRep(data: tiff), let png = rep.representation(using: .png, properties: [:]) {
            let hash = SHA256.hash(data: png).prefix(10).map { String(format: "%02x", $0) }.joined()
            let name = "\(hash).png"
            let file = imagesDir.appendingPathComponent(name)
            try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
            if !FileManager.default.fileExists(atPath: file.path) {
                guard (try? png.write(to: file)) != nil else { return }
            }
            item = ClipItem(kind: .image, text: "Imagem \(rep.pixelsWide)×\(rep.pixelsHigh)", imageFile: name)
        }

        guard var new = item else { return }
        new.sourceApp = front?.localizedName
        new.sourceBundle = front?.bundleIdentifier
        insert(new)
        PasteQueue.shared.captured(new)
        if new.kind == .image { queueOCR() }
    }

    // MARK: Texto das imagens

    static let ocrKey = "clipboardOCR"
    private var ocrRunning = false

    /// Lê o texto das imagens que ainda não foram lidas, uma por vez e sem pressa (as mais novas primeiro)
    func queueOCR() {
        guard !ocrRunning, !isDemo, defaults.object(forKey: Self.ocrKey) as? Bool ?? true,
              let item = items.first(where: { $0.kind == .image && $0.ocrText == nil }),
              let file = item.imageFile else { return }
        ocrRunning = true
        let url = imagesDir.appendingPathComponent(file)
        Task {
            let text = await Task.detached(priority: .background) { await TextRecognizer.recognize(url: url) }.value
            if let i = items.firstIndex(where: { $0.id == item.id }) {
                items[i].ocrText = text.trimmingCharacters(in: .whitespacesAndNewlines)
                save()
            }
            ocrRunning = false
            // Um respiro entre imagens para não pesar no Mac quando há muitas antigas para ler
            try? await Task.sleep(for: .seconds(1))
            queueOCR()
        }
    }

    private func insert(_ new: ClipItem) {
        var item = new
        if let idx = items.firstIndex(where: { $0.sameContent(as: new) }) {
            item.id = items[idx].id
            item.pinned = items[idx].pinned
            items.remove(at: idx)
        }
        items.insert(item, at: 0)
        prune()
        save()
    }

    /// Limite de quantidade e, se configurado, de idade. Fixados nunca saem.
    private func prune() {
        let maxItems = max(defaults.integer(forKey: "maxItems"), 20)
        let days = defaults.integer(forKey: "autoDeleteDays")
        let cutoff = days > 0 ? Date().addingTimeInterval(-Double(days) * 86_400) : nil
        var unpinned = 0
        var removed: [ClipItem] = []
        items.removeAll { item in
            guard !item.pinned else { return false }
            unpinned += 1
            if unpinned > maxItems || cutoff.map({ item.date < $0 }) == true { removed.append(item); return true }
            return false
        }
        removed.forEach(deleteImageIfOrphan)
    }

    private func deleteImageIfOrphan(_ item: ClipItem) {
        guard let f = item.imageFile, !items.contains(where: { $0.imageFile == f }) else { return }
        try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(f))
    }

    var ignoredApps: Set<String> {
        Set((defaults.string(forKey: "ignoredApps") ?? "").split(separator: ",").map {
            $0.trimmingCharacters(in: .whitespaces)
        })
    }

    // MARK: Busca

    func filtered(_ query: String, _ filter: ClipFilter = .all) -> [ClipItem] {
        if filter == .snippets { return snippets.items(matching: query) }
        if filter == .passwords { return passwordItems(matching: query) }
        let q = query.trimmingCharacters(in: .whitespaces)
        let base = items.filter(filter.matches)
        let matches = q.isEmpty ? base : base.filter { item in
            [item.text, item.sourceApp, item.ocrText].compactMap { $0 }.contains {
                $0.range(of: q, options: [.caseInsensitive, .diacriticInsensitive]) != nil
            }
        }
        // Busca pelo sentido e por data/tipo ("o link do hotel de ontem") vem depois dos que batem pelo texto
        let smart = q.isEmpty ? [] : SmartClipSearch.extra(q, in: base, excluding: Set(matches.map(\.id)))
        return matches.filter(\.pinned) + matches.filter { !$0.pinned } + smart
    }

    // MARK: Ações

    func copy(_ item: ClipItem) {
        write(item)
        // Sobe o item pro topo, como se tivesse acabado de ser copiado
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: idx)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    /// Põe o item no clipboard sem mexer na ordem do histórico
    func write(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            let text = item.text ?? ""
            pb.setString(item.snippetTitle != nil ? SnippetStore.expand(text) : text, forType: .string)
        case .file:
            let urls = (item.text ?? "").split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            pb.writeObjects(urls)
        case .image:
            if let f = item.imageFile, let img = NSImage(contentsOf: imagesDir.appendingPathComponent(f)) {
                pb.writeObjects([img])
            }
        }
        lastChange = pb.changeCount
    }

    /// O que está no clipboard agora foi escrito pelo próprio Menew e não entra no histórico
    func ignoreCurrentChange() { lastChange = NSPasteboard.general.changeCount }

    /// Copia texto novo (ex.: transformado) e registra no histórico
    func copyText(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        // deixa o poll capturar normalmente
    }

    // MARK: Senhas

    /// De onde vêm as notas de senhas (nas capturas de tela, das notas fictícias)
    var passwordNotes: () -> [Note] = { (NSApp.delegate as? AppDelegate)?.notes.notes ?? [] }

    /// As notas de senhas, só pelo título (o conteúdo fica trancado nas Chaves)
    func passwordItems(matching query: String) -> [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        return passwordNotes()
            .filter { $0.isPasswords && (q.isEmpty || $0.title.range(of: q, options: [.caseInsensitive, .diacriticInsensitive]) != nil) }
            .sorted { $0.updated > $1.updated }
            .map { ClipItem(id: $0.id, kind: .text, text: "••••••••\n" + L("↩ cola a senha · ⌥↩ cola o usuário. O Mac pede a sua digital antes."),
                            snippetTitle: $0.title, secretNoteID: $0.id) }
    }

    /// Pede o Touch ID, cola a senha (ou o usuário) no app da frente e tira do clipboard depois de 30 s.
    /// Vai marcada como confidencial: o Menew e outros gerenciadores de clipboard não guardam.
    func pasteSecret(_ id: UUID, username: Bool) {
        guard let notes = (NSApp.delegate as? AppDelegate)?.notes else { return }
        let target = WindowManager.shared.previousApp ?? NSWorkspace.shared.frontmostApplication
        let wasOpen = !notes.isLocked(id)
        Task { @MainActor in
            guard await notes.unlock(id) else { return }
            let fields = SecretField.parse(notes.text(of: id)).fields
            if !wasOpen { notes.lock(id) }
            guard let value = Self.secretValue(fields, username: username), !value.isEmpty else {
                HUD.show(icon: "key.fill", color: .orange, text: username ? L("Essa nota não tem usuário") : L("Essa nota não tem senha"))
                return
            }
            SecretCopy.copy(value)
            lastChange = NSPasteboard.general.changeCount
            guard defaults.bool(forKey: "autoPaste"), AXIsProcessTrusted() else {
                HUD.show(icon: "key.fill", color: .green, text: L("Copiado · some em 30 s"))
                return
            }
            target?.activate()
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.35) { Self.postCommandV() }
        }
    }

    /// O campo de senha (ou de usuário) pelo nome, em qualquer idioma; sem nome conhecido, a senha é o último campo
    /// e o usuário, o primeiro
    static func secretValue(_ fields: [SecretField], username: Bool) -> String? {
        let names = username
            ? ["usuário", "usuario", "user", "username", "login", "e-mail", "email", "benutzer", "用户", "账号", "conta", "account"]
            : ["senha", "password", "passwort", "contraseña", "contrasena", "密码", "pass", "pin", "token", "chave", "key", "secret"]
        let fold = { (s: String) in s.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil) }
        if let f = fields.first(where: { f in names.contains { fold(f.key).contains(fold($0)) } }) { return f.value }
        let filled = fields.filter { !$0.value.isEmpty }
        return username ? (filled.count > 1 ? filled.first?.value : nil) : filled.last?.value
    }

    /// Copia e simula ⌘V no app que estava na frente
    func paste(_ item: ClipItem, plainText: Bool = false) {
        if let id = item.secretNoteID { pasteSecret(id, username: plainText); return }
        // Snippets: pergunta os campos {input:…}, cola e põe o cursor onde estava o {cursor}
        if item.snippetTitle != nil, let raw = item.text {
            let target = WindowManager.shared.previousApp ?? NSWorkspace.shared.frontmostApplication
            let asked = !SnippetStore.fields(in: raw).isEmpty
            guard let filled = SnippetStore.fill(raw) else { return }
            let (text, back) = SnippetStore.expandWithCursor(filled)
            let pb = NSPasteboard.general
            pb.clearContents()
            pb.setString(text, forType: .string)
            lastChange = pb.changeCount
            guard defaults.bool(forKey: "autoPaste") else { return }
            guard AXIsProcessTrusted() else { Self.requestAccessibility(); return }
            if asked { target?.activate() }
            DispatchQueue.main.asyncAfter(deadline: .now() + (asked ? 0.35 : 0.12)) {
                Self.postCommandV()
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) { SnippetStore.moveCursorBack(back) }
            }
            return
        }
        if plainText, let t = item.text {
            copyText(item.snippetTitle != nil ? SnippetStore.expand(t) : t)
            lastChange = NSPasteboard.general.changeCount
        } else {
            copy(item)
        }
        guard defaults.bool(forKey: "autoPaste") else { return }
        guard AXIsProcessTrusted() else {
            Self.requestAccessibility()
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) { Self.postCommandV() }
    }

    static func postCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    // MARK: Pausa

    /// "paused": até retomar. "pausedUntil": volta sozinha nessa hora (segundos desde 1970).
    static var isPaused: Bool {
        let d = UserDefaults.standard
        return d.bool(forKey: "paused") || d.double(forKey: "pausedUntil") > Date().timeIntervalSince1970
    }

    static func pause(minutes: Int?) {
        let d = UserDefaults.standard
        if let minutes {
            d.set(false, forKey: "paused")
            d.set(Date().addingTimeInterval(TimeInterval(minutes * 60)).timeIntervalSince1970, forKey: "pausedUntil")
        } else {
            d.set(true, forKey: "paused")
            d.removeObject(forKey: "pausedUntil")
        }
    }

    static func resume() {
        UserDefaults.standard.set(false, forKey: "paused")
        UserDefaults.standard.removeObject(forKey: "pausedUntil")
    }

    static func requestAccessibility() {
        let opts = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }

    func togglePin(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteImageIfOrphan(item)
        save()
    }

    func clear(keepPinned: Bool = true) {
        let removed = items.filter { !keepPinned || !$0.pinned }
        items.removeAll { !keepPinned || !$0.pinned }
        removed.forEach(deleteImageIfOrphan)
        save()
    }

    func thumbnail(for item: ClipItem) -> NSImage? {
        guard let f = item.imageFile else { return nil }
        if let c = thumbCache.object(forKey: f as NSString) { return c }
        guard let img = NSImage(contentsOf: imagesDir.appendingPathComponent(f)) else { return nil }
        thumbCache.setObject(img, forKey: f as NSString)
        return img
    }

    func imageURL(for item: ClipItem) -> URL? {
        item.imageFile.map { imagesDir.appendingPathComponent($0) }
    }

    // MARK: Persistência

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        // Remove imagens cujo arquivo sumiu (ex.: capturadas durante a troca de nome do app)
        items = decoded.filter { item in
            guard let f = item.imageFile else { return true }
            return FileManager.default.fileExists(atPath: imagesDir.appendingPathComponent(f).path)
        }
        if items.count != decoded.count { save() }
        // Imagens de antes desta versão também ficam buscáveis
        DispatchQueue.main.asyncAfter(deadline: .now() + 10) { [weak self] in self?.queueOCR() }
    }

    private func save() {
        guard !isDemo else { return }
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}
